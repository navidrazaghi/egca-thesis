# ================================================================ chapter 3
def chapter3(b):
    b.H1("مبانی نظری و فرمول‌بندی مسئله")
    b.P("در این فصل، مبانی نظری لازم برای طراحی معماری پیشنهادی ارائه می‌شود. "
        "ابتدا مسئله رانندگی انتها-به-انتها در چارچوب یادگیری تقلیدی به‌صورت "
        "ریاضی صورت‌بندی می‌شود؛ سپس ساختار رمزگذارهای تک‌وجهی تصویر و ابر "
        "نقاط، سازوکار توجه و گونه کارآمد خطی آن، و در پایان چارچوب یادگیری "
        "چندوظیفه‌ای و توابع هزینه تشریح می‌شوند. نمادگذاری معرفی‌شده در این "
        "فصل، در سراسر فصل‌های بعد به کار می‌رود.")

    b.H2("فرمول‌بندی مسئله رانندگی انتها-به-انتها")
    b.P("محیط رانندگی را می‌توان یک [[فرایند تصمیم مارکوف مشاهده‌پذیر جزئی|"
        "Partially Observable Markov Decision Process (POMDP)]] در نظر گرفت که "
        "در آن عامل به حالت کامل محیط دسترسی ندارد و تنها مشاهده چندوجهی "
        "زیر را دریافت می‌کند:")
    b.EQ(r"o_t = \left( I_t, P_t, v_t, c_t, x_t^{\mathrm{goal}} \right)")
    b.P("که در آن {$I_t$} تصویر (یا تصاویر) دوربین، {$P_t$} ابر نقاط لیدار، {$v_t$} سرعت "
        "لحظه‌ای خودرو، {$c_t$} فرمان ناوبری سطح بالا (مانند «در تقاطع بعد به چپ "
        "بپیچ») و {$x_t^{\\mathrm{goal}}$} هدف تنک ناوبری در دستگاه مختصات بدنی خودرو است. "
        "به‌طور دقیق، سیاست بهینه در یک POMDP تابعی از باور، یعنی توزیع پسین "
        "حالت به‌شرط تمام تاریخ مشاهدات، است. در این پژوهش — همانند اکثر "
        "روش‌های مرجع [11و12] — باور با مشاهده لحظه‌ای تقریب زده می‌شود و سیاست "
        "بی‌حافظه (تک‌قابی) در نظر گرفته می‌شود؛ سرعت لحظه‌ای و فرمان ناوبری، "
        "بخشی از اطلاعات تاریخی لازم را به‌صورت فشرده تأمین می‌کنند. این تقریب، "
        "توانایی مدل در استدلال زمانی مانند پیش‌بینی اشیای مسدودشده را محدود "
        "می‌کند و در بخش ۶‌.‌۳ به‌عنوان یکی از محدودیت‌های پژوهش بازبینی "
        "می‌شود [6و25].")
    b.P("هدف، یادگیری سیاست پارامتری {$\\pi_\\theta$} است که مشاهده را به یک مسیر "
        "کوتاه‌مدت می‌نگارد و فرمان کنترلی پیوسته با یک نگاشت ثابت و بدون پارامتر "
        "آموختنی (دو کنترل‌کننده PID بخش ۴‌.‌۵) از آن مسیر استخراج می‌شود:")
    b.EQ(r"W_t = \pi_\theta (o_t), \qquad a_t = \mathrm{Ctrl} \left( W_t, v_t \right), "
         r"\qquad a_t = (\delta_t, \tau_t, \beta_t)")
    b.P("که {$\\delta_t$} زاویه غربیلک، {$\\tau_t$} دریچه گاز و {$\\beta_t$} ترمز است، و به پیروی از "
        "روش‌های موفق اخیر [11و12و24]، خروجی شبکه مجموعه‌ای از "
        "[[نقاط مسیر|Waypoints]] آینده در دستگاه مختصات بدنی خودرو است:")
    b.EQ(r"W_t = \left\{ w_{t+k} \right\}_{k=1}^{T}, \qquad w_{t+k} \in \mathbb{R}^{2}")
    b.P("این جداسازی، پایداری آموزش را افزایش می‌دهد و خروجی شبکه را "
        "تفسیرپذیرتر می‌کند [25]. در چارچوب یادگیری تقلیدی، یک خبره ممتاز "
        "{$\\pi^{*}$} — که در شبیه‌ساز به حالت کامل محیط دسترسی دارد [15] — "
        "مجموعه‌داده‌ای از مشاهده‌ها همراه با مسیر مرجع و برچسب‌های کمکی "
        "(نقشه قطعه‌بندی نمای پرنده {$S^{*}$} و نقشه عمق {$D^{*}$}) تولید می‌کند:")
    b.EQ(r"\mathcal{D} = \left\{ \left( o^{(i)}, W^{*(i)}, S^{*(i)}, D^{*(i)} \right) "
         r"\right\}_{i=1}^{M}")
    b.P("و پارامترهای سیاست با کمینه‌سازی خطای تقلید، یعنی فاصله میان مسیر "
        "پیش‌بینی‌شده و مسیر خبره، آموخته می‌شوند:")
    b.EQ(r"\theta^{*} = \arg\min_{\theta} \; \mathbb{E}_{o \sim d_{\pi^{*}}} "
         r"\left[ \mathcal{L}_{\mathrm{IL}} \left( \pi_\theta (o), W^{*}(o) \right) \right]")
    b.P("نکته مهم آنکه امید ریاضی در این رابطه روی توزیع حالت‌های بازدیدشده "
        "توسط خبره، {$d_{\\pi^{*}}$}، گرفته می‌شود، در حالی که در زمان اجرا توزیع "
        "حالت‌ها توسط خود سیاست آموخته‌شده، {$d_{\\pi_\\theta}$}، تعیین می‌شود. این عدم "
        "تطابق که [[انحراف توزیع|Covariate Shift]] نام دارد، منشأ تجمیع خطا در "
        "افق‌های بلند در یادگیری تقلیدی است [14]؛ در پژوهش حاضر اثر آن با "
        "افزودن اغتشاش به مسیر خبره هنگام جمع‌آوری داده و با ارزیابی حلقه‌بسته "
        "(نه حلقه‌باز) سنجیده و مهار می‌شود، اما به‌طور کامل حذف نمی‌شود.")

    b.H2("استخراج ویژگی از تصویر")
    b.P("برای استخراج ویژگی‌های معنایی از تصویر ورودی، از شبکه‌های پیچشی باقیمانده "
        "[[رزنت|ResNet]] استفاده می‌شود [16]. ایده اصلی این معماری، یادگیری نگاشت "
        "باقیمانده به جای نگاشت مستقیم است؛ هر بلوک باقیمانده خروجی زیر را "
        "تولید می‌کند:")
    b.EQ(r"y = \mathcal{F} (x, \{ W_i \}) + x")
    b.P("که در آن {$x$} ورودی بلوک و {$\\mathcal{F}$} نگاشت باقیمانده متشکل از دو یا سه لایه پیچشی "
        "است. اتصال میان‌بر همانی، مشکل محوشدگی گرادیان را در شبکه‌های عمیق "
        "برطرف می‌کند و امکان آموزش شبکه‌های بسیار عمیق را فراهم می‌سازد. با "
        "اعمال رمزگذار تصویری {$\\phi_c$} بر تصویر ورودی، نقشه ویژگی فشرده زیر حاصل "
        "می‌شود:")
    b.EQ(r"F_c = \phi_c (I_t) \in \mathbb{R}^{N_c \times d}")
    b.P("که {$N_c$} تعداد نشانه‌های فضایی حاصل از مسطح‌سازی نقشه ویژگی و {$d$} بعد "
        "مشترک نشانه‌ها است. در معماری پیشنهادی از ResNet-34 به‌عنوان ستون فقرات "
        "تصویری استفاده می‌شود که مصالحه مناسبی میان دقت و هزینه محاسباتی روی "
        "سکوهای بلادرنگ دارد.")

    b.H2("استخراج ویژگی از ابر نقاط لیدار")
    b.P("ابر نقاط لیدار مجموعه‌ای بی‌ترتیب و تُنُک از نقاط سه‌بعدی است و "
        "نمی‌توان آن را مستقیماً به شبکه‌های پیچشی داد. در این پژوهش از رویکرد "
        "[[ستون‌های نقطه‌ای|PointPillars]] [17] استفاده می‌شود که ابر نقاط را در "
        "ستون‌های عمودی شبکه‌بندی و به یک شبه‌تصویر نمای پرنده تبدیل می‌کند؛ "
        "روند کلی در " + fig_ref(3, 1) + " نشان داده شده‌است. هر نقطه درون یک "
        "ستون، ابتدا با آماره‌های هندسی ستون تقویت می‌شود:")
    b.EQ(r"\tilde{p}_i = \left[ x_i, y_i, z_i, r_i, x_i - \bar{x}, y_i - \bar{y}, "
         r"z_i - \bar{z}, x_i - x_p, y_i - y_p \right]")
    b.P("که {$(\\bar{x}, \\bar{y}, \\bar{z})$} مرکز جرم نقاط ستون و {$(x_p, y_p)$} مرکز هندسی ستون است. "
        "سپس یک شبکه PointNet ساده، ویژگی هر ستون را با بیشینه‌گیری متقارن روی "
        "نقاط آن استخراج می‌کند:")
    b.EQ(r"f_p = \max_{i \in \mathrm{pillar}} \; \mathrm{MLP} ( \tilde{p}_i )")
    b.P("عملگر بیشینه، ناوردایی نسبت به جایگشت نقاط را تضمین می‌کند. ویژگی‌های "
        "ستون‌ها در مکان اصلی خود در شبکه دوبعدی قرار می‌گیرند و یک ستون فقرات "
        "پیچشی سبک، نقشه ویژگی نمای پرنده را تولید می‌کند:")
    b.EQ(r"F_l = \phi_l (P_t) \in \mathbb{R}^{N_l \times d}")
    b.FIG("fig3_2_bev.png", "رمزگذاری ابر نقاط لیدار به نقشه ویژگی نمای پرنده")
    b.P("مزیت این نمایش آن است که نشانه‌های حاصل، ساختار فضایی صحنه را در "
        "دستگاه مختصات بدنی حفظ می‌کنند و هم‌ترازی آنها با نقاط مسیر خروجی، "
        "یادگیری نگاشت ادراک-برنامه‌ریزی را ساده می‌کند [2].")

    b.H2("سازوکار توجه")
    b.P("سازوکار توجه، هسته اصلی معماری ترنسفورمر [9] و ابزار اصلی ترکیب "
        "اطلاعات در این پژوهش است. در این بخش ابتدا شکل پایه توجه و سپس "
        "گونه‌های چندسر، متقابل و خطی آن معرفی می‌شوند.")
    b.H3("توجه ضرب داخلی مقیاس‌شده")
    b.P("توجه را می‌توان بازیابی نرم اطلاعات از یک حافظه دانست. با داشتن ماتریس "
        "پرسمان Q، کلید K و مقدار V، خروجی توجه ضرب داخلی مقیاس‌شده به‌صورت "
        "زیر تعریف می‌شود [9]:")
    b.EQ(r"\mathrm{Att} (Q, K, V) = \mathrm{softmax} \left( \frac{Q K^{\top}}"
         r"{\sqrt{d_k}} \right) V")
    b.P("که در آن {$Q \\in \\mathbb{R}^{N_q \\times d_k}$}، {$K \\in \\mathbb{R}^{N_k \\times d_k}$} و {$V \\in \\mathbb{R}^{N_k \\times d_v}$} است و "
        "مقیاس‌کننده {$\\sqrt{d_k}$} از اشباع تابع softmax در ابعاد بزرگ جلوگیری می‌کند. "
        "عنصر {$(i,j)$} ماتریس وزن توجه، میزان ارتباط پرسمان {$i$}-ام با کلید {$j$}-ام را "
        "به‌صورت نرمال‌شده بیان می‌کند:")
    b.EQ(r"A_{ij} = \frac{\exp \left( q_i^{\top} k_j / \sqrt{d_k} \right)}"
         r"{\sum_{j'=1}^{N_k} \exp \left( q_i^{\top} k_{j'} / \sqrt{d_k} \right)}")
    b.H3("توجه چندسر")
    b.P("برای آنکه مدل بتواند هم‌زمان به زیرفضاهای نمایشی متفاوت توجه کند، توجه "
        "به‌صورت چندسر اعمال می‌شود؛ ساختار آن در " + fig_ref(3, 2) +
        " نشان داده شده‌است:")
    b.EQ(r"\mathrm{head}_h = \mathrm{Att} \left( Q W_h^{Q}, \; K W_h^{K}, \; "
         r"V W_h^{V} \right)")
    b.EQ(r"\mathrm{MHA} (Q, K, V) = \mathrm{Concat} \left( \mathrm{head}_1, "
         r"\ldots, \mathrm{head}_H \right) W^{O}")
    b.P("که {$W_h^{Q}$}، {$W_h^{K}$}، {$W_h^{V}$} و {$W^{O}$} ماتریس‌های وزن آموختنی هستند و {$H$} "
        "تعداد سرها است.")
    b.FIG("fig3_1_attention.png",
          "سازوکار توجه ضرب داخلی مقیاس‌شده و توجه متقابل چندسر")
    b.H3("توجه متقابل بین‌وجهی")
    b.P("در [[خودتوجهی|Self-Attention]] هر سه ماتریس از یک دنباله واحد ساخته "
        "می‌شوند؛ اما در [[توجه متقابل|Cross-Attention]]، پرسمان‌ها از یک وجه و "
        "کلیدها و مقدارها از وجه دیگر می‌آیند. به‌طور مشخص، برای غنی‌سازی "
        "ویژگی‌های تصویر با اطلاعات هندسی لیدار داریم:")
    b.EQ(r"\tilde{F}_c = \mathrm{MHA} \left( F_c W^{Q}, \; F_l W^{K}, \; F_l W^{V} \right)")
    b.P("این سازوکار به هر نشانه تصویری اجازه می‌دهد به‌صورت انتخابی از "
        "نشانه‌های لیدار که بیشترین ارتباط زمینه‌ای را دارند، اطلاعات جذب کند؛ "
        "قابلیتی که ترکیب‌های الحاقی ساده فاقد آن هستند [10].")
    b.H3("پیچیدگی محاسباتی و توجه خطی")
    b.P("محاسبه توجه کامل چندسر نیازمند {$\\mathcal{O}(N_q N_k d)$} عملیات ضرب-جمع و "
        "{$\\mathcal{O}(H N_q N_k)$} خانه حافظه برای نگه‌داری ماتریس‌های وزن است؛ برای "
        "نقشه‌های ویژگی متراکم دو حسگر، این هزینه مرتبه دوم به گلوگاه محاسباتی "
        "تبدیل می‌شود. کاتارُپولوس و همکاران [18] نشان دادند که اگر شباهت نمایی "
        "با یک هسته تجزیه‌پذیر جایگزین شود، ترتیب ضرب ماتریس‌ها قابل تغییر است. "
        "با نگاشت ویژگی {$\\phi(\\cdot)$}، سطر {$i$}-ام خروجی توجه خطی چنین نوشته می‌شود:")
    b.EQ(r"\mathrm{LinAtt} (Q, K, V)_i = \frac{\left( \sum_{j=1}^{N_k} "
         r"\phi (k_j) v_j^{\top} \right)^{\!\top} \phi (q_i)}"
         r"{\phi (q_i)^{\top} \sum_{j=1}^{N_k} \phi (k_j)} \in \mathbb{R}^{d_v}")
    b.P("که در آن نگاشت ویژگی اکیداً مثبت زیر به کار می‌رود [18]:")
    b.EQ(r"\phi (x) = \mathrm{elu} (x) + 1")
    b.P("از آنجا که دو جمع روی {$j$} مستقل از {$i$} هستند، تنها یک بار محاسبه "
        "می‌شوند؛ در نتیجه، با در نظر گرفتن {$H$} سر با بعد {$d_h = d/H$}، پیچیدگی کل "
        "لایه به‌صورت زیر تغییر می‌کند:")
    b.EQ(r"\mathcal{O} \left( N_q N_k d \right) \; \longrightarrow \; "
         r"\mathcal{O} \left( (N_q + N_k) \, d_h \, d \right)")
    b.P("بنابراین توجه خطی تنها هنگامی ارزان‌تر است که شرط سربه‌سری زیر برقرار "
        "باشد؛ شرطی که مستقل از {$d$} است و صرفاً بعد هر سر را با میانگین هماهنگ "
        "تعداد نشانه‌ها مقایسه می‌کند:")
    b.EQ(r"N_q N_k \; > \; \frac{1}{2} \left( N_q + N_k \right) d_h")
    b.P("این نکته اهمیت عملی دارد: در وضوح‌های پایین (چند ده نشانه) توجه کامل "
        "ارزان‌تر است و خطی‌سازی سودی ندارد؛ مزیت آن تنها در ناحیه‌ای ظاهر "
        "می‌شود که {$N_q, N_k \\gg d_h$} باشد. در معماری پیشنهادی فصل چهارم با "
        "{$N_q N_k$} از مرتبه {$1.8 \\times 10^{6}$} و {$d_h = 64$}، این نسبت حدود ۱۲ برابر "
        "است. تحلیل تفصیلی بازنویسی هسته‌ای و شمارش دقیق عملیات در پیوست الف "
        "ارائه شده‌است.")
    b.P("تأکید بر یک نکته نظری ضروری است: توجه خطی " + eq_ref(3, 16) +
        " تقریبی از توجه softmax نیست، بلکه سازوکار توجه دیگری با هسته شباهت "
        "متفاوت است؛ زیرا هسته {$\\phi(q)^{\\top}\\phi(k)$} با {$\\phi(x)=\\mathrm{elu}(x)+1$} هسته نمایی را "
        "بازتولید نمی‌کند. تنها خاصیتی که حفظ می‌شود، نامنفی‌بودن وزن‌ها و "
        "نرمال‌شدن آنها به مجموع یک است، یعنی همان تفسیر «میانگین وزن‌دار "
        "محدب» از مقدارها. در مقابل، Performer [19] با هسته‌های تصادفی مثبت "
        "تقریبی نااریب از softmax فراهم می‌کند، اما به قیمت واریانس تقریب و "
        "نشانه‌های تصادفی اضافی؛ در آزمایش‌های مقدماتی این پژوهش، نگاشت قطعی "
        + eq_ref(3, 17) + " پایداری آموزشی بهتری نشان داد و به همین دلیل "
        "انتخاب شد.")
    b.H3("رمزگذاری موقعیت")
    b.P("سازوکار توجه نسبت به ترتیب نشانه‌ها ناوردا است؛ بنابراین اطلاعات "
        "موقعیت باید به‌صورت صریح تزریق شود. در این پژوهش از رمزگذاری سینوسی "
        "استاندارد [9] استفاده می‌شود:")
    b.EQ(r"\mathrm{PE} (pos, 2i) = \sin \left( \frac{pos}{10000^{2i/d}} \right), \qquad "
         r"\mathrm{PE} (pos, 2i+1) = \cos \left( \frac{pos}{10000^{2i/d}} \right)")
    b.P("برای نشانه‌های تصویر، این رمزگذاری روی مختصات دوبعدی شبکه ویژگی و "
        "برای نشانه‌های لیدار روی مختصات متریک BEV اعمال می‌شود تا هم‌ترازی "
        "هندسی دو وجه در فضای نهفته تسهیل شود.")

    b.H2("یادگیری چندوظیفه‌ای و توابع هزینه")
